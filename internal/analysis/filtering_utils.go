// ---------- Path-based detection ----------

func matchesAnyGlob(path string, patterns []string) bool {
	p := filepath.ToSlash(path)
	for _, pat := range patterns {
		match, err := doublestar.PathMatch(pat, p)
		if err == nil && match {
			return true
		}
	}
	return false
}

func hasTestLikePath(path string, language model.Language) bool {
	switch language {
	case model.Go:
		// Go uses its own patterns only (like Rust implementation)
		return matchesAnyGlob(path, goTestPathPatterns)

	case model.Java:
		// Java: default test folders only
		return matchesAnyGlob(path, defaultTestPaths)

	case model.Python:
		// Python: default folders + default filenames + extra pytest/nose/behave patterns
		var patterns []string
		patterns = append(patterns, defaultTestPaths...)
		patterns = append(patterns, defaultTestFilenames...)
		patterns = append(patterns, pythonTestPathPatterns...)
		return matchesAnyGlob(path, patterns)

	case model.JavaScript:
		// JavaScript: default folders + default filenames (*.test.js, *.spec.js) + Jest-specific
		var patterns []string
		patterns = append(patterns, defaultTestPaths...)
		patterns = append(patterns, defaultTestFilenames...)
		patterns = append(patterns, javascriptTestPathPatterns...)
		return matchesAnyGlob(path, patterns)

	case model.TypeScript:
		// TypeScript: same shape as JS — default folders + filenames + Jest mocks for ts/tsx/mts/cts
		var patterns []string
		patterns = append(patterns, defaultTestPaths...)
		patterns = append(patterns, defaultTestFilenames...)
		patterns = append(patterns, typescriptTestPathPatterns...)
		return matchesAnyGlob(path, patterns)

	case model.Kotlin:
		// Kotlin: default folders + filenames + Kotlin naming (FooTest.kt, FooSpec.kt)
		var patterns []string
		patterns = append(patterns, defaultTestPaths...)
		patterns = append(patterns, defaultTestFilenames...)
		patterns = append(patterns, kotlinTestPathPatterns...)
		return matchesAnyGlob(path, patterns)

	case model.PHP:
		// PHP: default folders + PHPUnit naming (FooTest.php, FooSpec.php)
		return matchesAnyGlob(path, slices.Concat(defaultTestPaths, defaultTestFilenames, phpTestPathPatterns))

	case model.Ruby:
		// Ruby: default folders + RSpec/Minitest naming
		return matchesAnyGlob(path, slices.Concat(defaultTestPaths, defaultTestFilenames, rubyTestPathPatterns))

	case model.Rust:
		// Rust: default folders (covers the "tests/" integration test dir) + tests.rs module convention
		return matchesAnyGlob(path, slices.Concat(defaultTestPaths, defaultTestFilenames, rustTestPathPatterns))

	case model.Elixir:
		return matchesAnyGlob(path, slices.Concat(defaultTestPaths, defaultTestFilenames, elixirTestPathPatterns))

	case model.Swift:
		return matchesAnyGlob(path, slices.Concat(defaultTestPaths, defaultTestFilenames, swiftTestPathPatterns))

	case model.Dart:
		return matchesAnyGlob(path, dartTestPathPatterns)

	default:
		// For other languages we don't classify here
		return false
	}
}

// ---------- Import-based detection ----------

func hasTestLikeImport(language model.Language, code, path string) bool {
	switch language {
	case model.Go:
		return goHasTestLikeImport(code, path)
	case model.Java:
		return javaHasTestLikeImport(code)
	case model.Python:
		return pythonHasTestLikeImport(code)
	case model.Kotlin:
		return kotlinHasTestLikeImport(code)
	case model.PHP:
		return phpHasTestLikeImport(code)
	case model.Ruby:
		return rubyHasTestLikeImport(code)
	case model.Elixir:
		return elixirHasTestLikeImport(code)
	case model.Swift:
		return swiftHasTestLikeImport(code)
	case model.Dart:
		return dartHasTestLikeImport(code)
	default:
		return false
	}
}

// ----- Go import detection -----

func goHasTestLikeImport(code, path string) bool {
	fset := token.NewFileSet()
	// Parse only imports; we don't need full AST.
	file, err := parser.ParseFile(fset, path, code, parser.ImportsOnly)
	if err != nil || file == nil {
		return false
	}

	testImportPrefixes := []string{
		"github.com/go-check/check",
		"github.com/onsi/ginkgo",
		"github.com/h2non/gock",
		"github.com/smartystreets/goconvey",
		"github.com/onsi/gomega",
		"github.com/golang/mock",
		"go.uber.org/mock",
		"github.com/petergtz/pegomock",
		"testing",
		"github.com/stretchr/testify",
	}

	for _, spec := range file.Imports {
		raw := strings.Trim(spec.Path.Value, `"`) // "testing" or "github.com/stretchr/testify/require"
		for _, prefix := range testImportPrefixes {
			if raw == prefix || strings.HasPrefix(raw, prefix+"/") {
				return true
			}
		}
	}
	return false
}

// ----- Java import detection -----
func javaHasTestLikeImport(code string) bool {
	javaTestPrefixes := []string{
		"org.apache.camel.test",
		"org.awaitility",
		"org.jboss.arquillian",
		"org.assertj",
		"io.cucumber",
		"org.dbunit",
		"org.easymock",
		"org.jbehave",
		"org.openjdk.jmh",
		"org.junit",
		"com.intuit.karate",
		"org.mockito",
		"au.com.dius.pact",
		"org.powermock",
		"io.restassured",
		"org.seleniumhq.selenium",
		"org.openqa.selenium",
		"org.spockframework",
		"org.testcontainers",
		"org.testfx",
		"org.testng",
		"com.github.tomakehurst.wiremock",
	}

	scanner := bufio.NewScanner(strings.NewReader(code))
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if !strings.HasPrefix(line, "import ") {
			continue
		}
		// Strip "import" and optional "static".
		line = strings.TrimSpace(strings.TrimPrefix(line, "import"))
		if strings.HasPrefix(line, "static ") {
			line = strings.TrimSpace(strings.TrimPrefix(line, "static"))
		}
		// Drop trailing ';'
		if i := strings.Index(line, ";"); i >= 0 {
			line = line[:i]
		}
		// Now line should be a FQN like org.junit.Assert or org.mockito.Mockito
		for _, prefix := range javaTestPrefixes {
			if line == prefix || strings.HasPrefix(line, prefix+".") {
				return true
			}
		}
	}
	return false
}

// ----- Kotlin import detection -----
func kotlinHasTestLikeImport(code string) bool {
	kotlinTestPrefixes := []string{
		"org.junit",
		"kotlin.test",
		"io.kotest",
		"io.kotlintest",
		"io.mockk",
		"org.mockito",
		"com.nhaarman.mockitokotlin2",
		"org.mockito.kotlin",
		"org.spekframework",
		"org.assertj",
		"org.amshove.kluent",
		"org.testng",
		"org.robolectric",
		"androidx.test",
	}

	scanner := bufio.NewScanner(strings.NewReader(code))
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if !strings.HasPrefix(line, "import ") {
			continue
		}
		// Strip "import" keyword (Kotlin imports have no trailing ';').
		line = strings.TrimSpace(strings.TrimPrefix(line, "import"))
		// Drop an "as alias" suffix, then a trailing ".*" wildcard.
		if i := strings.IndexByte(line, ' '); i >= 0 {
			line = line[:i]
		}
		line = strings.TrimSuffix(line, ".*")
		// Now line should be a FQN like org.junit.jupiter.api.Test
		for _, prefix := range kotlinTestPrefixes {
			if line == prefix || strings.HasPrefix(line, prefix+".") {
				return true
			}
		}
	}
	return false
}

// ----- Python import detection -----
func pythonHasTestLikeImport(code string) bool {
	pyTestPrefixes := []string{
		"behave",
		"doctest",
		"hypothesis",
		"nox",
		"pytest",
		"pytest_bdd",
		"testify",
		"unittest",
		"unittest2",
	}

	scanner := bufio.NewScanner(strings.NewReader(code))
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}

		// Handle "import X" or "import X as Y"
		if strings.HasPrefix(line, "import ") {
			rest := strings.TrimSpace(strings.TrimPrefix(line, "import"))
			// Basic split: "pytest", "pytest as p"
			fields := strings.Fields(rest)
			if len(fields) > 0 {
				mod := fields[0] // first module in "import pytest"
				if pythonImportMatches(mod, pyTestPrefixes) {
					return true
				}
			}
		}

		// Handle "from X import Y"
		if strings.HasPrefix(line, "from ") {
			rest := strings.TrimSpace(strings.TrimPrefix(line, "from"))
			fields := strings.Fields(rest)
			if len(fields) > 0 {
				mod := fields[0] // module in "from pytest import some_fixture"
				if pythonImportMatches(mod, pyTestPrefixes) {
					return true
				}
			}
		}
	}
	return false
}

func pythonImportMatches(module string, prefixes []string) bool {
	for _, prefix := range prefixes {
		if module == prefix || strings.HasPrefix(module, prefix+".") {
			return true
		}
	}
	return false
}

// ----- PHP import detection -----
func phpHasTestLikeImport(code string) bool {
	// PHP uses "use Vendor\Namespace\Class;" statements.
	phpTestPrefixes := []string{
		"PHPUnit\\",
		"Mockery\\",
		"Codeception\\",
		"Behat\\",
		"Prophecy\\",
		"AspectMock\\",
	}

	scanner := bufio.NewScanner(strings.NewReader(code))
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if !strings.HasPrefix(line, "use ") {
			continue
		}
		rest := strings.TrimSpace(strings.TrimPrefix(line, "use"))
		// Drop trailing ';'
		if i := strings.Index(rest, ";"); i >= 0 {
			rest = rest[:i]
		}
		// Drop "as Alias" suffix
		if i := strings.Index(rest, " as "); i >= 0 {
			rest = rest[:i]
		}
		rest = strings.TrimSpace(rest)
		for _, prefix := range phpTestPrefixes {
			if strings.HasPrefix(rest, prefix) {
				return true
			}
		}
	}
	return false
}

// ----- Ruby import detection -----
func rubyHasTestLikeImport(code string) bool {
	// Ruby uses require/require_relative for loading test frameworks.
	rubyTestLibs := []string{
		"rspec",
		"minitest",
		"test/unit",
		"shoulda",
		"cucumber",
		"capybara",
		"factory_bot",
		"faker",
	}

	scanner := bufio.NewScanner(strings.NewReader(code))
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		// Match: require 'rspec', require "minitest/autorun", require_relative 'spec_helper'
		if !strings.HasPrefix(line, "require") {
			continue
		}
		for _, lib := range rubyTestLibs {
			if strings.Contains(line, lib) {
				return true
			}
		}
	}
	return false
}

// ----- Elixir test framework detection -----
func elixirHasTestLikeImport(code string) bool {
	elixirTestPatterns := []string{
		"use ExUnit.Case",
		"use ExUnit.CaseTemplate",
		"import ExUnit.Assertions",
	}

	for _, pattern := range elixirTestPatterns {
		if strings.Contains(code, pattern) {
			return true
		}
	}
	return false
}

func swiftHasTestLikeImport(code string) bool {
	swiftTestModules := map[string]struct{}{
		"XCTest": {},
		"Quick":  {},
		"Nimble": {},
	}

	scanner := bufio.NewScanner(strings.NewReader(code))
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		line = strings.TrimPrefix(line, "@testable ")
		if !strings.HasPrefix(line, "import ") {
			continue
		}
		fields := strings.Fields(strings.TrimPrefix(line, "import"))
		if len(fields) == 0 {
			continue
		}
		module := fields[len(fields)-1]
		if i := strings.IndexByte(module, '.'); i >= 0 {
			module = module[:i]
		}
		if _, ok := swiftTestModules[module]; ok {
			return true
		}
	}
	return false
}

func dartHasTestLikeImport(code string) bool {
	testPackages := []string{
		"package:test/",
		"package:flutter_test/",
		"package:integration_test/",
		"package:mockito/",
		"package:mocktail/",
	}
	return containsAnyString(code, testPackages)
}

func containsAnyString(value string, candidates []string) bool {
	for _, candidate := range candidates {
		if strings.Contains(value, candidate) {
			return true
		}
	}
	return false
}
